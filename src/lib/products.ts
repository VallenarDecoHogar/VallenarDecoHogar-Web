// Helper para formatear precios en CLP (pesos chilenos, sin decimales)
export function formatCLP(value: number): string {
  return new Intl.NumberFormat("es-CL", {
    style: "currency",
    currency: "CLP",
    maximumFractionDigits: 0,
  }).format(value);
}

// Helper para aplicar markup dinámicamente y redondear hacia arriba
// Usado por el admin panel para recalcular precios cuando cambian los markups
export function applyMarkup(
  originalPrice: number,
  settings: { lowMarkup: number; highMarkup: number; threshold: number },
): { price: number; oldPrice: number } {
  const markup = originalPrice < settings.threshold ? settings.lowMarkup : settings.highMarkup;
  const marked = originalPrice * (1 + markup / 100);
  // Redondeo hacia arriba a múltiplos limpios según magnitud
  let rounded: number;
  if (marked < 2000) rounded = Math.ceil(marked / 50) * 50;
  else if (marked < 10000) rounded = Math.ceil(marked / 100) * 100;
  else if (marked < 50000) rounded = Math.ceil(marked / 500) * 500;
  else if (marked < 100000) rounded = Math.ceil(marked / 1000) * 1000;
  else rounded = Math.ceil(marked / 5000) * 5000;
  // Old price para mostrar tachado (+25% extra)
  const old = rounded * 1.25;
  let oldRounded: number;
  if (old < 10000) oldRounded = Math.ceil(old / 100) * 100;
  else if (old < 50000) oldRounded = Math.ceil(old / 500) * 500;
  else if (old < 100000) oldRounded = Math.ceil(old / 1000) * 1000;
  else oldRounded = Math.ceil(old / 5000) * 5000;
  return { price: rounded, oldPrice: oldRounded };
}

