// Un producto es "nuevo" si tiene addedAt y fue agregado en los últimos NEW_PRODUCT_DAYS días
export const NEW_PRODUCT_DAYS = 30;

export function isNewProduct(p: Product, days: number = NEW_PRODUCT_DAYS): boolean {
  if (!p.addedAt) return false;
  const addedDate = new Date(p.addedAt);
  if (isNaN(addedDate.getTime())) return false;
  const now = new Date();
  const diffMs = now.getTime() - addedDate.getTime();
  const diffDays = diffMs / (1000 * 60 * 60 * 24);
  return diffDays <= days;
}

// Devuelve los productos nuevos/recientes ordenados por fecha (más reciente primero)
export function getRecentProducts(limit?: number): Product[] {
  const recent = products
    .filter((p) => p.addedAt)
    .sort((a, b) => {
      const dateA = new Date(a.addedAt!).getTime();
      const dateB = new Date(b.addedAt!).getTime();
      return dateB - dateA;
    });
  return limit ? recent.slice(0, limit) : recent;
}

// Formatea la fecha en español (ej: "Hace 3 días", "Hace 1 semana")
export function formatRelativeDate(isoDate: string): string {
  const date = new Date(isoDate);
  if (isNaN(date.getTime())) return "";
  const now = new Date();
  const diffMs = now.getTime() - date.getTime();
  const diffDays = Math.floor(diffMs / (1000 * 60 * 60 * 24));
  if (diffDays <= 0) return "Hoy";
  if (diffDays === 1) return "Ayer";
  if (diffDays < 7) return `Hace ${diffDays} días`;
  if (diffDays < 14) return "Hace 1 semana";
  if (diffDays < 30) return `Hace ${Math.floor(diffDays / 7)} semanas`;
  if (diffDays < 60) return "Hace 1 mes";
  return `Hace ${Math.floor(diffDays / 30)} meses`;
}
